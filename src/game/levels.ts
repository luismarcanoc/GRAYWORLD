import type { Hazard, Level, Platform, Rect, WorldTheme } from "./types";

const floor = (x: number, w: number, tint = 0): Platform => ({ x, y: 480, w, h: 60, tint });
const ledge = (x: number, y: number, w: number, id?: string, tint = 0): Platform => ({ x, y, w, h: 20, id, tint });
const spikes = (x: number, y = 456, w = 48, dangerousTo: "yin" | "yang" | "both" = "both"): Hazard => ({
  x,
  y,
  w,
  h: 24,
  kind: "spikes",
  dangerousTo,
});
const zone = (x: number, y: number, w: number, h: number, dangerousTo: "yin" | "yang"): Hazard => ({
  x,
  y,
  w,
  h,
  kind: "field",
  dangerousTo,
});
const door = (x: number, forPlayer: "yin" | "yang", y = 424): Rect & { for: "yin" | "yang" } => ({
  x,
  y,
  w: 36,
  h: 56,
  for: forPlayer,
});

